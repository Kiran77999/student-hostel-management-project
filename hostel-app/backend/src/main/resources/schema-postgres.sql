CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 roll_no VARCHAR(40) NOT NULL UNIQUE, phone VARCHAR(20) NOT NULL, department VARCHAR(80) NOT NULL,
 password VARCHAR(100) NOT NULL, role VARCHAR(15) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, block_name VARCHAR(30) NOT NULL, number VARCHAR(20) NOT NULL,
 capacity INT NOT NULL, monthly_fee DECIMAL(12,2) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
 UNIQUE(block_name, number));
CREATE TABLE IF NOT EXISTS allocations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL UNIQUE, room_id BIGINT NOT NULL,
 allocated_on DATE NOT NULL, FOREIGN KEY(student_id) REFERENCES users(id), FOREIGN KEY(room_id) REFERENCES rooms(id));
CREATE TABLE IF NOT EXISTS invoices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL, description VARCHAR(150) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, due_date DATE NOT NULL, paid BOOLEAN NOT NULL DEFAULT FALSE,
 paid_on DATE, reference_no VARCHAR(100), FOREIGN KEY(student_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS complaints (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL, category VARCHAR(30) NOT NULL,
 subject VARCHAR(150) NOT NULL, details VARCHAR(2000) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 response VARCHAR(1000) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(student_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS leave_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL, from_date DATE NOT NULL,
 to_date DATE NOT NULL, reason VARCHAR(1000) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 response VARCHAR(1000) NOT NULL DEFAULT '', FOREIGN KEY(student_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS notices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(150) NOT NULL, body VARCHAR(2000) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL, attendance_date DATE NOT NULL,
 status VARCHAR(20) NOT NULL, UNIQUE(student_id, attendance_date), FOREIGN KEY(student_id) REFERENCES users(id));
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor VARCHAR(160) NOT NULL, action VARCHAR(200) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
